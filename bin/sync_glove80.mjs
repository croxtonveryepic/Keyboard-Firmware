import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parseKeymap } from "../visualizer/src/keymap-parser.mjs";
import { glove80Hands, mapGlove80Layer } from "./glove80-layout.mjs";

const sourceUrl = new URL("../config/adv360.keymap", import.meta.url);
const outputUrl = new URL("../config/glove80/glove80.keymap", import.meta.url);
const keymap = parseKeymap(await readFile(sourceUrl, "utf8"));
if (keymap.warnings.length || keymap.hasInvalidLayers || keymap.layers.length !== 7) {
  throw new Error(`Cannot map Advantage keymap: ${JSON.stringify(keymap)}`);
}

const lines = [
  "// Generated by node bin/sync_glove80.mjs from config/adv360.keymap.",
  "// See README.md: Glove80 layout mapping and hardware adaptations.",
  "#define GLOVE80 1",
  `#define LEFT_HAND_KEYS ${glove80Hands.left.join(" ")}`,
  `#define RIGHT_HAND_KEYS ${glove80Hands.right.join(" ")}`,
  `#define THUMB_KEYS ${glove80Hands.thumbs.join(" ")}`,
  '#include "../keyboard-behaviors.dtsi"',
  "",
  "/ {",
  "    keymap {",
  '        compatible = "zmk,keymap";',
];
for (const layer of keymap.layers) {
  lines.push(
    "",
    `        ${layer.nodeName} {`,
    `            display-name = ${JSON.stringify(layer.name)};`,
    "            bindings = <",
    ...mapGlove80Layer(layer).map((row) => `                ${row.join("  ")}`),
    "            >;",
    "        };",
  );
}
lines.push("", '        extra4 { display-name = "Yellow"; status = "reserved"; };', "    };", "};", "");
const output = lines.join("\n");
if (process.argv.includes("--check")) {
  if (await readFile(outputUrl, "utf8") !== output) {
    throw new Error("Glove80 keymap is stale. Run node bin/sync_glove80.mjs.");
  }
  console.log("Glove80 keymap is in sync (7 layers, 80 keys each).");
} else {
  await writeFile(outputUrl, output);
  console.log(`Updated ${fileURLToPath(outputUrl)}`);
}
